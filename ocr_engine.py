"""
ocr_engine.py
Handles image preprocessing (deskew, denoise, contrast) and ROI-based
OCR extraction for the Amrita pink evaluation sheet.

Design notes
------------
The sheet is a fixed printed template, so once a scan is normalized into a
canonical (fixed width/height, upright, cropped-to-page) image, every field
sits at the same *relative* position across all scans. We therefore:

  1. Normalize the input photo -> canonical image.
  2. Look up each field's rectangle from roi_config.json, where every
     rectangle is stored as fractions (0..1) of canonical width/height.
  3. Crop just that rectangle and run EasyOCR on the small crop only,
     instead of OCR-ing the whole page (this is what the brief asked for -
     it both speeds things up and boosts accuracy, since EasyOCR does not
     have to search a big noisy image for a tiny handwritten digit).

roi_config.json is NOT guessed pixel-by-pixel by hand here; it's meant to be
produced once via the calibration page (/calibrate) by clicking rectangles on
a real scanned sheet. A reasonable starter config is generated by
generate_default_roi_config() so the app runs out of the box, but you should
recalibrate against your own scanner/phone output for real accuracy.
"""

import os
import json
import cv2
import numpy as np
import easyocr

ROI_CONFIG_PATH = os.path.join(os.path.dirname(__file__), "roi_config.json")
CANONICAL_W = 1400
CANONICAL_H = 1900

_reader = None


def get_reader():
    """Lazily load EasyOCR reader (slow to init, so do it once)."""
    global _reader
    if _reader is None:
        _reader = easyocr.Reader(["en"], gpu=False)
    return _reader


# ---------------------------------------------------------------------------
# Preprocessing
# ---------------------------------------------------------------------------

def order_points(pts):
    rect = np.zeros((4, 2), dtype="float32")
    s = pts.sum(axis=1)
    rect[0] = pts[np.argmin(s)]
    rect[2] = pts[np.argmax(s)]
    diff = np.diff(pts, axis=1)
    rect[1] = pts[np.argmin(diff)]
    rect[3] = pts[np.argmax(diff)]
    return rect


def find_page_contour(gray):
    """Try to find the largest quadrilateral (the sheet) in the image."""
    blurred = cv2.GaussianBlur(gray, (5, 5), 0)
    edged = cv2.Canny(blurred, 50, 150)
    edged = cv2.dilate(edged, np.ones((5, 5), np.uint8), iterations=2)
    contours, _ = cv2.findContours(edged, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
    contours = sorted(contours, key=cv2.contourArea, reverse=True)[:5]
    for c in contours:
        peri = cv2.arcLength(c, True)
        approx = cv2.approxPolyDP(c, 0.02 * peri, True)
        if len(approx) == 4 and cv2.contourArea(approx) > 0.3 * gray.shape[0] * gray.shape[1]:
            return approx.reshape(4, 2)
    return None


def warp_to_canonical(image):
    """Deskew + perspective-correct + resize the sheet to a fixed canvas."""
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    quad = find_page_contour(gray)

    if quad is not None:
        rect = order_points(quad.astype("float32"))
        dst = np.array(
            [[0, 0], [CANONICAL_W - 1, 0], [CANONICAL_W - 1, CANONICAL_H - 1], [0, CANONICAL_H - 1]],
            dtype="float32",
        )
        M = cv2.getPerspectiveTransform(rect, dst)
        warped = cv2.warpPerspective(image, M, (CANONICAL_W, CANONICAL_H))
    else:
        # Fallback: no clean quad found, just resize the whole frame.
        warped = cv2.resize(image, (CANONICAL_W, CANONICAL_H))

    return warped


def auto_rotate_if_sideways(image):
    """
    Phone photos of these sheets are frequently rotated 90 degrees (as in the
    sample). Heuristic: a portrait-oriented printed form scanned sideways
    produces a wide landscape photo. If width > height * 1.15, try rotating
    90 deg clockwise and let the caller's contour step verify.
    """
    h, w = image.shape[:2]
    if w > h * 1.15:
        return cv2.rotate(image, cv2.ROTATE_90_CLOCKWISE)
    return image


def denoise_and_contrast(image):
    lab = cv2.cvtColor(image, cv2.COLOR_BGR2LAB)
    l, a, b = cv2.split(lab)
    clahe = cv2.createCLAHE(clipLimit=2.5, tileGridSize=(8, 8))
    l = clahe.apply(l)
    merged = cv2.merge((l, a, b))
    enhanced = cv2.cvtColor(merged, cv2.COLOR_LAB2BGR)
    enhanced = cv2.fastNlMeansDenoisingColored(enhanced, None, 5, 5, 7, 21)
    return enhanced


def preprocess(image_path):
    image = cv2.imread(image_path)
    if image is None:
        raise ValueError(f"Could not read image: {image_path}")
    image = auto_rotate_if_sideways(image)
    image = denoise_and_contrast(image)
    canonical = warp_to_canonical(image)
    return canonical


# ---------------------------------------------------------------------------
# ROI config
# ---------------------------------------------------------------------------

def generate_default_roi_config():
    """
    Rough starter layout based on the known field positions on the Amrita
    pink sheet (Sl.No box top-right area post-rotation, question grid in
    the middle-left, three blocks of 10 questions x a/b rows, subtotal
    column, grand total near bottom). These are FRACTIONS of canonical
    width/height and are meant to be replaced via /calibrate.
    """
    cfg = {
        "canonical_width": CANONICAL_W,
        "canonical_height": CANONICAL_H,
        "rois": {
            "sl_no": {"x": 0.55, "y": 0.03, "w": 0.30, "h": 0.05},
            "grand_total": {"x": 0.55, "y": 0.86, "w": 0.20, "h": 0.05},
            "subtotals": {},
            "questions": {},
        },
    }

    # 3 blocks of 10 questions (1-10, 11-20, 21-30), each with a/b rows.
    block_top = [0.28, 0.50, 0.72]
    row_h = 0.045
    col_w = 0.075
    grid_left = 0.06
    for block_idx, top in enumerate(block_top):
        start_q = block_idx * 10 + 1
        for col in range(10):
            qnum = start_q + col
            x = grid_left + col * col_w
            cfg["rois"]["questions"][f"{qnum}a"] = {
                "x": round(x, 4), "y": round(top, 4), "w": col_w, "h": row_h
            }
            cfg["rois"]["questions"][f"{qnum}b"] = {
                "x": round(x, 4), "y": round(top + row_h, 4), "w": col_w, "h": row_h
            }
        cfg["rois"]["subtotals"][f"block{block_idx + 1}"] = {
            "x": grid_left + 10 * col_w, "y": round(top, 4), "w": 0.10, "h": row_h * 2
        }

    return cfg


def load_roi_config():
    if not os.path.exists(ROI_CONFIG_PATH):
        cfg = generate_default_roi_config()
        save_roi_config(cfg)
        return cfg
    with open(ROI_CONFIG_PATH, "r") as f:
        return json.load(f)


def save_roi_config(cfg):
    with open(ROI_CONFIG_PATH, "w") as f:
        json.dump(cfg, f, indent=2)


# ---------------------------------------------------------------------------
# Cropping + OCR
# ---------------------------------------------------------------------------

def crop_roi(canonical_image, roi_frac):
    h, w = canonical_image.shape[:2]
    x = int(roi_frac["x"] * w)
    y = int(roi_frac["y"] * h)
    rw = int(roi_frac["w"] * w)
    rh = int(roi_frac["h"] * h)
    x, y = max(0, x), max(0, y)
    rw, rh = max(1, rw), max(1, rh)
    return canonical_image[y:y + rh, x:x + rw]


def ocr_crop(crop, allowlist=None):
    """Run EasyOCR on a single small crop, return (text, confidence 0-100)."""
    reader = get_reader()
    if crop.size == 0:
        return "", 0.0
    # Upscale small handwriting crops for better recognition.
    crop = cv2.resize(crop, None, fx=3.0, fy=3.0, interpolation=cv2.INTER_CUBIC)
    kwargs = {"detail": 1, "paragraph": False}
    if allowlist:
        kwargs["allowlist"] = allowlist
    results = reader.readtext(crop, **kwargs)
    if not results:
        return "", 0.0
    # Pick the highest-confidence detection in the crop.
    results.sort(key=lambda r: r[2], reverse=True)
    text = " ".join(r[1] for r in results).strip()
    conf = max(r[2] for r in results) * 100
    return text, round(conf, 1)


def clean_numeric(text):
    """Extract a plausible mark value (int or one-decimal float) from OCR text."""
    text = text.strip().replace("O", "0").replace("o", "0")
    keep = "".join(ch for ch in text if ch.isdigit() or ch == ".")
    if not keep:
        return None
    try:
        val = float(keep)
        if val == int(val):
            return int(val)
        return val
    except ValueError:
        return None


def extract_sheet(image_path):
    """
    Full pipeline: preprocess -> crop each configured ROI -> OCR -> assemble
    structured JSON with per-field confidence.
    """
    canonical = preprocess(image_path)
    cfg = load_roi_config()

    result = {
        "booklet_number": None,
        "booklet_number_confidence": 0.0,
        "questions": {},
        "subtotals": {},
        "grand_total": None,
        "grand_total_confidence": 0.0,
        "calculated_total": 0,
    }

    sl_crop = crop_roi(canonical, cfg["rois"]["sl_no"])
    text, conf = ocr_crop(sl_crop, allowlist="ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
    result["booklet_number"] = text.replace(" ", "").upper()
    result["booklet_number_confidence"] = conf

    total = 0
    for qkey, roi in cfg["rois"]["questions"].items():
        crop = crop_roi(canonical, roi)
        text, conf = ocr_crop(crop, allowlist="0123456789.")
        val = clean_numeric(text)
        result["questions"][qkey] = {
            "raw_text": text,
            "value": val,
            "confidence": conf,
        }
        if val is not None:
            total += val
    result["calculated_total"] = round(total, 2)

    for bkey, roi in cfg["rois"].get("subtotals", {}).items():
        crop = crop_roi(canonical, roi)
        text, conf = ocr_crop(crop, allowlist="0123456789.")
        val = clean_numeric(text)
        result["subtotals"][bkey] = {"raw_text": text, "value": val, "confidence": conf}

    gt_crop = crop_roi(canonical, cfg["rois"]["grand_total"])
    text, conf = ocr_crop(gt_crop, allowlist="0123456789.")
    result["grand_total"] = clean_numeric(text)
    result["grand_total_confidence"] = conf

    result["mismatch"] = (
        result["grand_total"] is not None
        and result["grand_total"] != result["calculated_total"]
    )

    return result, canonical
